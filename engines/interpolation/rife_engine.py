"""
AI frame interpolation with RIFE (rife-ncnn-vulkan - the same engine family Flowframes uses).

Pipeline (bounded memory and disk, any video length):
    FFmpeg decoder --raw RGB pipe--> segments of N frames --PNG--> RIFE --PNG--> FFmpeg encoder (+ original audio)

Segments share one boundary frame, so motion across segment borders is interpolated like everywhere else.
Real AI interpolation only: frames are generated by the model, never blended or duplicated
(except the very last source frame, which is held for its own duration).
"""
import math
import os
import shutil
import tempfile
import time
from dataclasses import dataclass, field
from fractions import Fraction

from core.errors import (DeviceError, DiskSpaceError, GpuMemoryError, StudioError, UnsupportedFormatError)
from core.process_manager import popen
from core.report import ValidationReport
from core.video_analyzer import VideoInfo, analyze
from . import gpu_manager, model_manager
from .frame_processor import FORMATS, PRESETS, FrameEncoder, FrameReader


@dataclass
class InterpolationJob:
    input_path: str
    output_path: str
    target_fps: Fraction
    model: str = "rife-v4.6"
    device: str = "auto"
    preset: str = "balanced"
    fmt: str = "MP4 · H.264"
    out_height: int | None = None
    segment_frames: int = 160          # "batch size": source frames per RIFE call
    preview_seconds: float | None = None


@dataclass
class InterpolationResult:
    output_path: str
    multiplier: int
    source_fps: Fraction
    output_fps: Fraction
    frames_in: int
    frames_generated: int
    elapsed: float
    report: ValidationReport
    notes: list = field(default_factory=list)


def plan_multiplier(src_fps: Fraction, target: Fraction) -> int:
    if target <= src_fps * Fraction(1001, 1000):
        raise StudioError(f"Target FPS ({float(target):g}) must be higher than the source FPS ({float(src_fps):.3f}).")
    return max(2, math.ceil(target / src_fps))


def _classify_rife_error(log: str, rc: int) -> StudioError:
    low = log.lower()
    if any(k in low for k in ("out of memory", "vkallocatememory", "vk_error_out_of", "failed to allocate")):
        return GpuMemoryError("Not enough GPU memory. Lower the output resolution, reduce the batch size, "
                              "or pick another model/device.\n\n" + log[-400:])
    if any(k in low for k in ("invalid gpu device", "no vulkan", "vkcreateinstance failed", "vulkan")):
        return DeviceError("The selected GPU could not be initialised (Vulkan). Update your graphics driver "
                           "or choose another device in the settings.\n\n" + log[-400:])
    return StudioError(f"RIFE failed (exit code {rc}):\n{log[-800:]}")


def run(job: InterpolationJob, progress, cancel) -> InterpolationResult:
    from PIL import Image

    t0 = time.time()
    notes: list = []
    if os.path.normcase(os.path.abspath(job.input_path)) == os.path.normcase(os.path.abspath(job.output_path)):
        raise StudioError("Refusing to overwrite the source video.")
    if job.fmt not in FORMATS:
        raise StudioError(f"Unknown output format '{job.fmt}'.")

    progress(0.0, "Analysing video…")
    info = analyze(job.input_path)
    if info.frame_count is None or not info.frame_count_exact:
        info = analyze(job.input_path, exact_frames=True)
    src_fps = info.fps
    mult = plan_multiplier(src_fps, Fraction(job.target_fps))
    if mult > 16:
        raise StudioError("Interpolation factors above 16× are not supported.")
    model = model_manager.get_model(job.model)
    if mult != 2 and not model.supports_arbitrary_multiplier:
        raise StudioError(f"{model.label} can only double the frame rate. Choose a RIFE v4.x model for {mult}×.")
    exe = model_manager.rife_executable()

    total_src = info.frame_count or int(info.duration * float(src_fps))
    max_frames = None
    if job.preview_seconds:
        max_frames = max(2, int(math.ceil(job.preview_seconds * float(src_fps))))
        total_src = min(total_src, max_frames)
    if info.is_vfr:
        notes.append(f"Variable frame rate detected: normalised to constant {float(src_fps):.3f} FPS before interpolation.")

    out_dir = os.path.dirname(os.path.abspath(job.output_path)) or "."
    os.makedirs(out_dir, exist_ok=True)
    seg = max(8, job.segment_frames)
    est_png = info.width * info.height * 3 * 0.75
    need = est_png * (seg + 1) * (1 + mult) + info.size_bytes * 2 + 300 * 1024 ** 2
    free = shutil.disk_usage(out_dir).free
    if free < need:
        raise DiskSpaceError(f"Not enough free disk space on the output drive: need ≈ {need / 1024 ** 3:.1f} GB, "
                             f"have {free / 1024 ** 3:.1f} GB. Reduce the batch size or free some space.")

    tmp = tempfile.mkdtemp(prefix=".ff_work_", dir=out_dir)
    seg_in, seg_out = os.path.join(tmp, "in"), os.path.join(tmp, "out")
    part = job.output_path + ".part"
    out_fps = Fraction(job.target_fps)
    reader = encoder = None
    frames_generated = 0
    try:
        _, _, rife_extra = PRESETS[job.preset]
        reader = FrameReader(job.input_path, info.width, info.height, src_fps, info.is_vfr,
                             max_frames, os.path.join(tmp, "decode.log"), cancel)
        encoder = FrameEncoder(part, src_fps * mult, out_fps, job.input_path, info.has_audio, info.audio_codec,
                               job.fmt, job.preset, job.out_height, job.preview_seconds,
                               os.path.join(tmp, "encode.log"), cancel)
        notes.append(f"{model.label}; {mult}× interpolation; batch of {seg} frames; device: {job.device}")

        carry = None
        read_total = 0
        while True:
            cancel.check()
            frames = [carry] if carry is not None else []
            fresh = 0
            while len(frames) < seg:
                raw = reader.read()
                if raw is None:
                    break
                frames.append(raw)
                fresh += 1
            read_total += fresh
            if fresh == 0:
                # only the carried boundary frame (or an empty video) is left
                if carry is not None:
                    encoder.write_file(_png(Image, carry, info, tmp), mult)
                break
            is_final = len(frames) < seg
            n = len(frames)
            if n == 1:                                   # one-frame video
                encoder.write_file(_png(Image, frames[0], info, tmp), mult)
                break

            for d in (seg_in, seg_out):
                shutil.rmtree(d, ignore_errors=True)
                os.makedirs(d)
            for i, raw in enumerate(frames, 1):
                Image.frombuffer("RGB", (info.width, info.height), raw, "raw", "RGB", 0, 1).save(
                    os.path.join(seg_in, f"{i:08d}.png"), compress_level=1)

            expected = (n - 1) * mult + 1
            cmd = [exe, "-i", seg_in, "-o", seg_out, "-m", str(model.path), "-n", str(expected)]
            cmd += gpu_manager.to_rife_gpu_arg(job.device) + gpu_manager.thread_arg(job.preset, job.device) + rife_extra
            log_path = os.path.join(tmp, "rife.log")
            with open(log_path, "w+", encoding="utf-8") as log:
                proc = popen(cmd, cwd=str(exe.parent), stdout=log, stderr=log)
                cancel.register(proc)
                base = (read_total - fresh) / max(total_src, 1)
                span = fresh / max(total_src, 1)
                while proc.poll() is None:
                    time.sleep(0.25)
                    cancel.check()
                    done = len(os.listdir(seg_out)) / expected
                    _report(progress, t0, base + span * min(done, 1.0), total_src, "Generating AI frames…")
                log.seek(0)
                rlog = log.read()
            if proc.returncode != 0:
                raise _classify_rife_error(rlog, proc.returncode)
            outs = sorted(f for f in os.listdir(seg_out) if f.lower().endswith(".png"))
            if len(outs) != expected:
                raise StudioError(f"RIFE produced {len(outs)} frames but {expected} were expected. "
                                  f"This model/version may not support {mult}× output.\n{rlog[-400:]}")
            keep = outs if is_final else outs[:-1]
            for f in keep:
                encoder.write_file(os.path.join(seg_out, f))
            if is_final:
                encoder.write_file(os.path.join(seg_out, outs[-1]), mult - 1)   # hold last source frame
                break
            carry = frames[-1]
            _report(progress, t0, read_total / max(total_src, 1), total_src, "Encoding…")

        decode_msg = reader.close()
        reader = None
        if decode_msg:
            raise StudioError("FFmpeg decoder reported problems:\n" + decode_msg[-600:])
        progress(0.97, "Finalising video…")
        encoder.finish()
        encoder = None
        os.replace(part, job.output_path)
    finally:
        if reader:
            reader.close()
        if encoder:
            try:
                encoder.proc.kill()
            except OSError:
                pass
        for p in (part,):
            if os.path.exists(p) and not os.path.exists(job.output_path):
                try:
                    os.remove(p)
                except OSError:
                    pass
        shutil.rmtree(tmp, ignore_errors=True)

    progress(0.99, "Validating output…")
    report = _validate(job, info, mult, out_fps, total_src, bool(job.preview_seconds))
    if not report.passed:
        raise StudioError("Output validation failed:\n\n" + report.text())
    progress(1.0, "Done")
    return InterpolationResult(job.output_path, mult, src_fps, out_fps, total_src, total_src * (mult - 1),
                               time.time() - t0, report, notes)


def _png(Image, raw: bytes, info: VideoInfo, tmp: str) -> str:
    p = os.path.join(tmp, "single.png")
    Image.frombuffer("RGB", (info.width, info.height), raw, "raw", "RGB", 0, 1).save(p, compress_level=1)
    return p


def _report(progress, t0, frac, total_src, text):
    el = time.time() - t0
    eta = el * (1 - frac) / frac if frac > 0.01 else None
    progress(frac * 0.96, text, eta=eta, fps=(frac * total_src / el if el > 1 else None))


def _validate(job, info: VideoInfo, mult: int, out_fps: Fraction, total_src: int, preview: bool) -> ValidationReport:
    rep = ValidationReport()
    try:
        out = analyze(job.output_path, exact_frames=True)
    except StudioError as e:
        rep.add("Output readable", False, str(e))
        return rep
    rep.add("Output readable", True, f"{out.resolution} · {out.video_codec}")
    exp_frames = round(total_src * float(out_fps) / float(info.fps))
    rep.add("Frames were generated", (out.frame_count or 0) > total_src,
            f"{total_src} source frames → {out.frame_count} output frames")
    rep.add("Output frame count", out.frame_count is not None and abs(out.frame_count - exp_frames) <= max(3, mult),
            f"{out.frame_count} (expected ≈ {exp_frames})")
    rep.add("Output frame rate", abs(float(out.fps) - float(out_fps)) / float(out_fps) < 0.01,
            f"{float(out.fps):.3f} FPS (target {float(out_fps):g})")
    if not preview:
        rep.add("Output duration", abs(out.duration - info.duration) < max(0.25, info.duration * 0.01),
                f"{out.duration:.2f}s (source {info.duration:.2f}s)")
        if info.has_audio:
            ad = out.audio_duration or 0.0
            vd = out.video_duration or out.duration
            rep.add("Audio synchronisation", out.has_audio and abs(ad - vd) < 0.25,
                    f"audio {ad:.2f}s / video {vd:.2f}s")
    return rep
